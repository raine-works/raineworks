/**
 * Thrown when packages in a bundle can't ship in the site: `packages` names each with why
 * (`name@version (no licence stated)`, `name@version (GPL-3.0-only)`).
 */
export class LicenseError extends Error {
	override readonly name = 'LicenseError' as const;

	constructor(readonly packages: string[]) {
		super(
			`Not licensed to ship in the MIT-licensed site: ${packages.join(', ')}. One that states no licence is named in LICENSE_OVERRIDES once someone has checked what it's under; one under a licence outside ALLOWED_LICENSES is replaced, or the licence allowed by whoever answers for licensing (@raineworks/tools/notices).`,
		);
	}
}

/**
 * Whether an SPDX expression can be met with {@link ALLOWED_LICENSES} alone: any one side of an `OR` (the choice is
 * ours), every side of an `AND`, which binds tighter, and a parenthesised group as one. Anything it can't read as
 * such an expression (an exception added `WITH`, "SEE LICENSE IN …", unbalanced parentheses) isn't allowed: it's
 * for a person to read.
 */
export function isAllowedLicense(expression: string): boolean {
	const tokens = expression.match(/[()]|[^\s()]+/g) ?? [];
	let at = 0;
	// Each returns whether what it read is allowed, or `null` when it isn't an expression.
	const term = (): boolean | null => {
		const token = tokens[at++];
		if (token === undefined || token === ')' || token === 'OR' || token === 'AND') return null;
		if (token !== '(') return ALLOWED_LICENSES.includes(token);
		const group = either();
		return tokens[at++] === ')' ? group : null;
	};
	const joined = (operator: 'AND' | 'OR', operand: () => boolean | null, join: (a: boolean, b: boolean) => boolean) => {
		let allowed = operand();
		while (allowed !== null && tokens[at] === operator) {
			at++;
			const next = operand();
			allowed = next === null ? null : join(allowed, next);
		}
		return allowed;
	};
	const both = (): boolean | null => joined('AND', term, (a, b) => a && b);
	const either = (): boolean | null => joined('OR', both, (a, b) => a || b);
	return either() === true && at === tokens.length;
}

const NODE_MODULES = '/node_modules/';
/** A package's licence and notice files (`LICENSE`, `LICENCE.md`, `COPYING`, `NOTICE.txt`, `LICENSE-MIT`). */
const LICENSE_FILE = /^(licen[sc]e|copying|notice)([.-]|$)/i;

/**
 * The directory of the installed package a file belongs to (the innermost `node_modules/<name>` above it), or
 * `null` for a file that's the project's own.
 */
export function packageDirOf(path: string): string | null {
	const at = path.lastIndexOf(NODE_MODULES);
	if (at === -1) return null;
	const [scope = '', name = ''] = path.slice(at + NODE_MODULES.length).split('/');
	return `${path.slice(0, at + NODE_MODULES.length)}${scope.startsWith('@') ? `${scope}/${name}` : scope}`;
}

/** A package's licence and notice files, one after another; `null` when it ships none. */
function licenseText(dir: string): string | null {
	const texts = readdirSync(dir)
		.filter((file) => LICENSE_FILE.test(file))
		.sort()
		.map((file) => readFileSync(join(dir, file), 'utf8').trim());
	return texts.isEmpty() ? null : texts.join('\n\n');
}

/**
 * The notices for a bundle: one per package (and version) its files come from, with {@link STYLE_PACKAGES} and
 * {@link COPIED_NOTICES}, by name.
 *
 * @param inputs - The bundle's files: the keys of its metafile's `inputs`, which are relative to the working
 *   directory the build ran in (this one).
 * @param overrides - Licences for packages that state none.
 * @throws {LicenseError} naming every package that states no licence (and has no override) or is under one
 *   outside {@link ALLOWED_LICENSES}.
 */
export function collectNotices(
	inputs: readonly string[],
	overrides: Readonly<Record<string, string>> = LICENSE_OVERRIDES,
): Notice[] {
	const dirs = [
		...inputs.map((input) => packageDirOf(resolve(input))),
		// As installed for `@raineworks/ui`: through its link, to the same directory a bundled file of it would name.
		...STYLE_PACKAGES.map((name) => realpathSync(join(UI_DIR, 'node_modules', name))),
	]
		.filter((dir) => dir !== null)
		.unique();
	const notices: Notice[] = [...COPIED_NOTICES];
	const refused: string[] = [];
	for (const dir of dirs) {
		const manifest = join(dir, 'package.json');
		// A directory under `node_modules` that isn't a package (a bundler's cache) is nobody's to credit.
		if (!existsSync(manifest)) continue;
		const { name, version, license } = JSON.parse(readFileSync(manifest, 'utf8')) as {
			name: string;
			version: string;
			license?: unknown;
		};
		const stated = typeof license === 'string' && license !== 'UNLICENSED' ? license.trim() : '';
		const known = overrides[name] ?? stated;
		if (known.isEmpty()) refused.push(`${name}@${version} (no licence stated)`);
		else if (!isAllowedLicense(known)) refused.push(`${name}@${version} (${known})`);
		else notices.push({ name, version, license: known, text: licenseText(dir) });
	}
	if (!refused.isEmpty()) throw new LicenseError(refused.sort());
	return notices
		.unique((notice) => `${notice.name}@${notice.version}`)
		.sort((a, b) => a.name.localeCompare(b.name) || (a.version ?? '').localeCompare(b.version ?? ''));
}
